#!/bin/bash
# RQ3: Hybrid Analysis Case Study on json-c
# Demonstrates synergy between static and dynamic analysis

set -e

SCRIPT_DIR="$( cd "$( dirname "${BASH_SOURCE[0]}" )" && pwd )"
OPTIWEAVE_BIN="${SCRIPT_DIR}/../../build/optiweave"
RESULTS_DIR="${SCRIPT_DIR}/../results/rq3"
JSON_C_DIR="${SCRIPT_DIR}/../benchmarks/case-studies/json-c"

mkdir -p "$RESULTS_DIR"

echo "RQ3: Hybrid Analysis Case Study - json-c"
echo "=========================================="
echo ""

if [ ! -d "$JSON_C_DIR" ]; then
    echo "Error: json-c not found. Run setup_case_study.sh first"
    exit 1
fi

cd "$JSON_C_DIR"

# Find all C source files
echo "Finding source files..."
find . -name "*.c" -not -path "*/build/*" -not -path "*/tests/*" > "$RESULTS_DIR/source_files.txt"
file_count=$(wc -l < "$RESULTS_DIR/source_files.txt")
echo "Found $file_count C source files"
echo ""

# Phase 1: Static Analysis
echo "Phase 1: Static Analysis"
echo "------------------------"

# Overflow detection
echo "  [1/4] Integer overflow detection..."
"$OPTIWEAVE_BIN" $(cat "$RESULTS_DIR/source_files.txt") \
    --detect-overflow -- > "$RESULTS_DIR/static_overflow.txt" 2>&1 || true

# FP precision warnings
echo "  [2/4] Floating-point precision analysis..."
"$OPTIWEAVE_BIN" $(cat "$RESULTS_DIR/source_files.txt") \
    --fp-precision-warnings -- > "$RESULTS_DIR/static_fp.txt" 2>&1 || true

# Data flow analysis
echo "  [3/4] Data flow analysis..."
"$OPTIWEAVE_BIN" $(cat "$RESULTS_DIR/source_files.txt") \
    --data-flow-analysis -- > "$RESULTS_DIR/static_dataflow.txt" 2>&1 || true

# Complexity analysis
echo "  [4/4] Complexity analysis..."
"$OPTIWEAVE_BIN" $(cat "$RESULTS_DIR/source_files.txt") \
    --analyze-complexity -- > "$RESULTS_DIR/static_complexity.txt" 2>&1 || true

echo "✓ Static analysis complete"
echo ""

# Phase 2: Dynamic Profiling (on test suite)
echo "Phase 2: Dynamic Profiling"
echo "--------------------------"
echo "  Note: Requires instrumenting and running json-c test suite"
echo "  This is a manual step - document findings in results"
echo ""

# Create findings template
cat > "$RESULTS_DIR/case_study_findings.md" << 'EOF'
